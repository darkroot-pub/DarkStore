package com.darkstore.utils

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import android.util.Log
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Encrypted key/value storage for secrets (Firebase ID token, refresh token, ...).
 *
 * Values are encrypted with AES-256-GCM using a key that lives in the Android Keystore
 * (hardware-backed where available) and can never be exported — so a rooted phone, an
 * adb backup, or a copied /data folder only ever shows ciphertext.
 *
 * Plain SharedPreferences stay for non-secret UI state. Anything that can impersonate
 * the user MUST go through this class.
 */
object SecureStore {
    private const val TAG = "SecureStore"
    private const val ANDROID_KEYSTORE = "AndroidKeyStore"
    private const val KEY_ALIAS = "darkstore_secure_prefs_v1"
    private const val PREFS = "dark_store_secure"
    private const val PREFIX = "enc1:"
    private const val LEGACY_PREFS = "dark_store_pref"

    /** Secret keys that used to live in plain prefs and must be migrated + wiped. */
    private val LEGACY_SECRET_KEYS = listOf("auth_id_token", "auth_refresh_token", "fcm_server_key")

    private fun secretKey(): SecretKey {
        val ks = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (ks.getKey(KEY_ALIAS, null) as? SecretKey)?.let { return it }
        val gen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        gen.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .build()
        )
        return gen.generateKey()
    }

    private fun encrypt(plain: String): String {
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, secretKey())
        val ct = cipher.doFinal(plain.toByteArray(Charsets.UTF_8))
        // 12-byte random IV is generated by the Keystore; store it in front of the ciphertext.
        return PREFIX + Base64.encodeToString(cipher.iv + ct, Base64.NO_WRAP)
    }

    private fun decrypt(stored: String): String? = try {
        if (!stored.startsWith(PREFIX)) null else {
            val raw = Base64.decode(stored.removePrefix(PREFIX), Base64.NO_WRAP)
            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(Cipher.DECRYPT_MODE, secretKey(), GCMParameterSpec(128, raw, 0, 12))
            String(cipher.doFinal(raw, 12, raw.size - 12), Charsets.UTF_8)
        }
    } catch (e: Exception) {
        // Key was invalidated / data corrupt: treat as "no value" (user simply signs in again).
        Log.w(TAG, "Could not decrypt a stored value; treating as empty")
        null
    }

    fun putString(context: Context, name: String, value: String) {
        val prefs = context.applicationContext.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        if (value.isEmpty()) { prefs.edit().remove(name).apply(); return }
        try {
            prefs.edit().putString(name, encrypt(value)).apply()
        } catch (e: Exception) {
            // Fail CLOSED: never fall back to storing the secret in plain text.
            Log.e(TAG, "Encryption unavailable; secret not persisted")
            prefs.edit().remove(name).apply()
        }
    }

    fun getString(context: Context, name: String, default: String = ""): String {
        val prefs = context.applicationContext.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        val stored = prefs.getString(name, null) ?: return default
        return decrypt(stored) ?: default
    }

    fun remove(context: Context, name: String) {
        context.applicationContext.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().remove(name).apply()
    }

    /** Wipe every stored credential (logout / account switch / guest mode). */
    fun clearAuth(context: Context) {
        remove(context, "auth_id_token")
        remove(context, "auth_refresh_token")
        // Also make sure no legacy plain copy survives.
        val legacy = context.applicationContext.getSharedPreferences(LEGACY_PREFS, Context.MODE_PRIVATE)
        legacy.edit().apply { LEGACY_SECRET_KEYS.forEach { remove(it) } }.apply()
    }

    /**
     * One-time upgrade: move tokens saved by older versions out of plain SharedPreferences
     * into encrypted storage, then delete the plain copies. Safe to call on every launch.
     */
    fun migrateLegacySecrets(context: Context) {
        val legacy = context.applicationContext.getSharedPreferences(LEGACY_PREFS, Context.MODE_PRIVATE)
        val ed = legacy.edit()
        var changed = false
        for (key in LEGACY_SECRET_KEYS) {
            if (!legacy.contains(key)) continue
            val v = legacy.getString(key, "") ?: ""
            // The server key is intentionally NOT kept anywhere any more.
            if (v.isNotBlank() && key != "fcm_server_key" && getString(context, key).isBlank()) {
                putString(context, key, v)
            }
            ed.remove(key)
            changed = true
        }
        if (changed) ed.apply()
    }
}
